export function getWorkSiteLocationDetails(taskDescription?: string, workSites: any[] = []): { address: string; city: string; fullLocation: string } {
  if (!taskDescription) return { address: "", city: "", fullLocation: "" };
  const clean = taskDescription.trim().toUpperCase();
  // 1. Cerca nei workSites forniti da context
  const ws = workSites.find(w => 
    w.name.toUpperCase() === clean || 
    clean.includes(w.name.toUpperCase()) || 
    w.name.toUpperCase().includes(clean)
  );
  if (ws && ws.address) {
    const full = [ws.address, ws.city].filter(Boolean).join(", ");
    return { address: ws.address, city: ws.city || "", fullLocation: full };
  }
  // 2. Cerca nel registro precaricato
  if (CANTIERI_REGISTRY[clean] && CANTIERI_REGISTRY[clean].address) {
    const entry = CANTIERI_REGISTRY[clean];
    const full = [entry.address, entry.city].filter(Boolean).join(", ");
    return { address: entry.address, city: entry.city, fullLocation: full };
  }
  // 3. Cerca per matching parziale
  for (const [key, val] of Object.entries(CANTIERI_REGISTRY)) {
    if (val.address && (clean.includes(key) || key.includes(clean))) {
      const full = [val.address, val.city].filter(Boolean).join(", ");
      return { address: val.address, city: val.city, fullLocation: full };
    }
  }
  return { address: ws?.address || "", city: ws?.city || "", fullLocation: [ws?.address, ws?.city].filter(Boolean).join(", ") };
}
